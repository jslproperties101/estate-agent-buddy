// JoyChange008: builds src/domain/myPlacesData.ts (Malaysia State > City / Town) from a postcode list.
// Accepts either
//   - the official MCMC postcode CSV from data.gov.my (columns include state, city/post_office, postcode), or
//   - the open JSON "AsyrafHussin/malaysia-postcodes" all.json ({ state: [{ name, city: [{ name, postcode: [] }] }] }).
// Usage: node scripts/build-my-places.mjs <path-to-file> [source-label]
// The output is small (state -> sorted town names) and ships inside the app, so the lists work offline.
import { readFileSync, writeFileSync } from 'node:fs';

const [, , file, label] = process.argv;
if (!file) { console.error('usage: node scripts/build-my-places.mjs <postcodes.csv | all.json> [source-label]'); process.exit(1); }

// The app's own state names (domain/places.ts MY_STATES): federal territories without "WP".
const STATE_NAME = s => {
  const t = s.trim().replace(/\s+/g, ' ');
  const low = t.toLowerCase().replace(/^(wp|w\.p\.|wilayah persekutuan)\s+/, '');
  const map = { 'kuala lumpur': 'Kuala Lumpur', 'labuan': 'Labuan', 'putrajaya': 'Putrajaya', 'penang': 'Pulau Pinang', 'pulau pinang': 'Pulau Pinang', 'malacca': 'Melaka', 'melaka': 'Melaka' };
  return map[low] ?? low.replace(/\b\w/g, c => c.toUpperCase());
};
const TOWN = s => s.trim().replace(/\s+/g, ' ');

const out = new Map();   // state -> Map(lowercase town -> town)
const add = (st, town) => {
  if (!st || !town) return;
  const s = STATE_NAME(st); const t = TOWN(town);
  if (!out.has(s)) out.set(s, new Map());
  const m = out.get(s); if (!m.has(t.toLowerCase())) m.set(t.toLowerCase(), t);
};

const raw = readFileSync(file, 'utf8');
if (file.endsWith('.json')) {
  for (const st of JSON.parse(raw).state) for (const c of st.city) add(st.name, c.name);
} else {
  const lines = raw.split(/\r?\n/).filter(Boolean);
  const head = lines[0].split(',').map(h => h.trim().toLowerCase().replace(/"/g, ''));
  const si = head.findIndex(h => h === 'state'); const ci = head.findIndex(h => h === 'city' || h === 'post_office' || h === 'town');
  if (si < 0 || ci < 0) { console.error(`CSV needs state and city columns; found: ${head.join(', ')}`); process.exit(1); }
  for (const line of lines.slice(1)) { const cols = line.split(',').map(x => x.replace(/^"|"$/g, '')); add(cols[si], cols[ci]); }
}

const states = [...out.keys()].sort((a, b) => a.localeCompare(b));
const body = states.map(s => `  ${JSON.stringify(s)}: ${JSON.stringify([...out.get(s).values()].sort((a, b) => a.localeCompare(b)))},`).join('\n');
const n = states.reduce((k, s) => k + out.get(s).size, 0);
writeFileSync(new URL('../src/domain/myPlacesData.ts', import.meta.url), `// GENERATED by scripts/build-my-places.mjs — do not edit by hand. JoyChange008: Malaysia State > City / Town.
// Source: ${label ?? file.split('/').pop()}. ${states.length} states and federal territories, ${n} cities / towns.
export const MY_PLACES_SOURCE = ${JSON.stringify(label ?? file.split('/').pop())};
export const MY_OFFICIAL_TOWNS: Record<string, readonly string[]> = {
${body}
};
`);
console.log(`wrote ${states.length} states, ${n} towns`);
